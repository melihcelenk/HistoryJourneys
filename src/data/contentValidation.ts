import type { ConceptSeed, FigureSeed, LineSeed, RelationTypeSeed } from '../domain/contentSchema';
import { extractLinks, findMalformedLinks } from '../domain/markup';

/** Everything the content files define, after schema validation. */
export interface ContentSeed {
  figures: FigureSeed[];
  relationTypes: RelationTypeSeed[];
  lines: LineSeed[];
}

/** Marks problems about a link to a figure that has no content file; the build can skip these while content is being written. */
export const UNKNOWN_FIGURE_LINK = 'link to unknown figure';

/**
 * Two definitions of one place may differ by at most this many degrees (about five kilometres): figure
 * files round coordinates differently. The database keeps the coordinates of the first definition.
 */
const PLACE_TOLERANCE_DEGREES = 0.05;

function findDuplicates(values: string[]): string[] {
  const seen = new Set<string>();
  const duplicates = new Set<string>();
  for (const value of values) {
    if (seen.has(value)) duplicates.add(value);
    seen.add(value);
  }
  return [...duplicates];
}

/** Every piece of generated text of a figure that may carry link markup. */
function textsOf(figure: FigureSeed): string[] {
  return [
    ...figure.summary,
    ...figure.actions.flatMap((action) => [action.text, action.cause, action.consequence, action.depth ?? '']),
  ];
}

function checkLinks(figure: FigureSeed, figureSlugs: Set<string>, conceptSlugs: Set<string>): string[] {
  return textsOf(figure).flatMap((text) => [
    ...findMalformedLinks(text).map((piece) => `${figure.slug}: malformed link markup "${piece}"`),
    ...extractLinks(text).flatMap((link) => {
      if (link.target === 'figure') {
        return figureSlugs.has(link.slug) ? [] : [`${figure.slug}: ${UNKNOWN_FIGURE_LINK} "${link.slug}"`];
      }
      return conceptSlugs.has(link.slug) ? [] : [`${figure.slug}: link to unknown concept "${link.slug}"`];
    }),
  ]);
}

function checkRelations(figure: FigureSeed, figureSlugs: Set<string>, typeNames: Set<string>): string[] {
  const perRelation = figure.relations.flatMap((relation) => {
    const errors: string[] = [];
    if (!figureSlugs.has(relation.to)) errors.push(`${figure.slug}: relation to unknown figure "${relation.to}"`);
    if (!typeNames.has(relation.type)) errors.push(`${figure.slug}: unknown relation type "${relation.type}"`);
    if (relation.to === figure.slug) errors.push(`${figure.slug}: relation to itself`);
    return errors;
  });
  const repeated = findDuplicates(figure.relations.map((relation) => `${relation.type} "${relation.to}"`));
  return [...perRelation, ...repeated.map((relation) => `${figure.slug}: duplicate relation ${relation}`)];
}

/** A relation that a line already generates must not be written by hand as well. */
function checkLineLinks(figures: FigureSeed[], lines: LineSeed[]): string[] {
  const generated = new Map<string, string>();
  for (const line of lines) {
    if (!line.linkType) continue;
    line.members.slice(1).forEach((member, index) => {
      generated.set(`${member}|${line.members[index]}|${line.linkType}`, line.slug);
    });
  }
  return figures.flatMap((figure) =>
    figure.relations.flatMap((relation) => {
      const line = generated.get(`${figure.slug}|${relation.to}|${relation.type}`);
      return line ? [`${figure.slug}: relation ${relation.type} "${relation.to}" is already generated by line ${line}`] : [];
    }),
  );
}

function checkIdentifiers(figure: FigureSeed): string[] {
  const sourceIds = new Set(figure.sources.map((source) => source.id));
  return [
    ...findDuplicates(figure.actions.map((action) => action.id)).map((id) => `${figure.slug}: duplicate action "${id}"`),
    ...findDuplicates(figure.sources.map((source) => source.id)).map((id) => `${figure.slug}: duplicate source "${id}"`),
    ...figure.actions.flatMap((action) =>
      action.sources
        .filter((id) => !sourceIds.has(id))
        .map((id) => `${figure.slug}: action "${action.id}" cites unknown source "${id}"`),
    ),
  ];
}

function checkLifespan(figure: FigureSeed): string[] {
  const errors: string[] = [];
  if (figure.death.year < figure.birth.year) errors.push(`${figure.slug}: death before birth`);
  if (figure.reign && figure.reign.to < figure.reign.from) errors.push(`${figure.slug}: reign ends before it starts`);
  return errors;
}

/** Journeys must be in chronological order; the map and the timeline rely on it. */
function checkJourney(figure: FigureSeed): string[] {
  const errors: string[] = [];
  figure.journey.forEach((stop, index) => {
    if (stop.to < stop.from) errors.push(`${figure.slug}: journey stop ${index + 1} ends before it starts`);
    const previous = figure.journey[index - 1];
    if (previous && stop.from < previous.from) errors.push(`${figure.slug}: journey stop ${index + 1} is out of order`);
  });
  return errors;
}

/** One place may be defined by several figures; all definitions must agree. */
function checkPlaces(figures: FigureSeed[]): string[] {
  const seen = new Map<string, { place: FigureSeed['journey'][number]['place']; owner: string }>();
  const errors = new Set<string>();
  for (const figure of figures) {
    for (const { place } of figure.journey) {
      const known = seen.get(place.slug);
      if (!known) {
        seen.set(place.slug, { place, owner: figure.slug });
        continue;
      }
      const moved =
        Math.abs(known.place.lat - place.lat) > PLACE_TOLERANCE_DEGREES ||
        Math.abs(known.place.lon - place.lon) > PLACE_TOLERANCE_DEGREES;
      if (moved) errors.add(`${figure.slug}: place "${place.slug}" has different coordinates than in ${known.owner}`);
      if (known.place.nameTr !== place.nameTr || known.place.historicName !== place.historicName) {
        errors.add(`${figure.slug}: place "${place.slug}" has a different name than in ${known.owner}`);
      }
    }
  }
  return [...errors];
}

/** One concept may be repeated by several figures, but only with the same definition. */
function checkConcepts(figures: FigureSeed[]): string[] {
  const seen = new Map<string, { concept: ConceptSeed; owner: string }>();
  const errors: string[] = [];
  for (const figure of figures) {
    for (const concept of figure.concepts) {
      const known = seen.get(concept.slug);
      if (!known) seen.set(concept.slug, { concept, owner: figure.slug });
      else if (JSON.stringify(known.concept) !== JSON.stringify(concept)) {
        errors.push(`${figure.slug}: concept "${concept.slug}" is defined differently than in ${known.owner}`);
      }
    }
  }
  return errors;
}

function checkLines(lines: LineSeed[], figureSlugs: Set<string>, typeNames: Set<string>): string[] {
  return lines.flatMap((line) => [
    ...line.members.filter((member) => !figureSlugs.has(member)).map((member) => `line ${line.slug}: unknown figure "${member}"`),
    ...(line.linkType && !typeNames.has(line.linkType) ? [`line ${line.slug}: unknown relation type "${line.linkType}"`] : []),
  ]);
}

/**
 * Cross-file consistency checks that the schema cannot express. Returns a list
 * of human-readable errors; an empty list means the content is consistent.
 * Every primary key of the database is checked for duplicates here, so that
 * the database build never has to guess which of two rows was meant.
 */
export function validateContent(seed: ContentSeed): string[] {
  const figureSlugs = new Set(seed.figures.map((figure) => figure.slug));
  const typeNames = new Set(seed.relationTypes.map((type) => type.type));
  const conceptSlugs = new Set(seed.figures.flatMap((figure) => figure.concepts.map((concept) => concept.slug)));
  return [
    ...findDuplicates(seed.figures.map((figure) => figure.slug)).map((slug) => `duplicate figure "${slug}"`),
    ...findDuplicates(seed.relationTypes.map((type) => type.type)).map((type) => `duplicate relation type "${type}"`),
    ...findDuplicates(seed.lines.map((line) => line.slug)).map((slug) => `duplicate line "${slug}"`),
    ...seed.figures.flatMap((figure) => [
      ...checkLinks(figure, figureSlugs, conceptSlugs),
      ...checkRelations(figure, figureSlugs, typeNames),
      ...checkIdentifiers(figure),
      ...checkLifespan(figure),
      ...checkJourney(figure),
    ]),
    ...checkLineLinks(seed.figures, seed.lines),
    ...checkPlaces(seed.figures),
    ...checkConcepts(seed.figures),
    ...checkLines(seed.lines, figureSlugs, typeNames),
  ];
}
