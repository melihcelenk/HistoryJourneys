import { existsSync } from 'node:fs';
import { join } from 'node:path';
import initSqlJs, { type SqlJsStatic } from 'sql.js';
import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import { SUGGESTED_JOURNEYS } from '../../src/app/suggestions';
import { buildDatabase } from '../../src/data/buildDatabase';
import { validateContent } from '../../src/data/contentValidation';
import { figureSchema } from '../../src/domain/contentSchema';
import { BUILT_AT, figureSeed, sampleSeed } from './fixtures';

let SQL: SqlJsStatic;

beforeAll(async () => {
  SQL = await initSqlJs();
});

afterEach(() => {
  vi.restoreAllMocks();
});

describe('validateContent: duplicates', () => {
  it('reports an action id used twice in one figure', () => {
    const seed = sampleSeed();
    seed.figures[1]!.actions[1]!.id = 'ilk';
    expect(validateContent(seed)).toContain('y: duplicate action "ilk"');
  });

  it('reports a source id used twice in one figure', () => {
    const seed = sampleSeed();
    seed.figures[1]!.sources[1]!.id = 's1';
    expect(validateContent(seed)).toContain('y: duplicate source "s1"');
  });

  it('reports the same relation written twice', () => {
    const seed = sampleSeed();
    seed.figures[0]!.relations.push({ to: 'y', type: 'child_of', note: 'tekrar' });
    expect(validateContent(seed)).toContain('x: duplicate relation child_of "y"');
  });

  it('reports a relation that repeats a link generated by a line', () => {
    const seed = sampleSeed();
    seed.figures[0]!.relations.push({ to: 'y', type: 'succeeded', note: 'elle yazılmış' });
    expect(validateContent(seed)).toContain('x: relation succeeded "y" is already generated by line hat');
  });

  it('reports duplicate relation types and lines', () => {
    const seed = sampleSeed();
    seed.relationTypes.push({ ...seed.relationTypes[0]! });
    seed.lines.push({ ...seed.lines[0]! });
    const errors = validateContent(seed);
    expect(errors).toContain('duplicate relation type "succeeded"');
    expect(errors).toContain('duplicate line "hat"');
  });

  it('accepts one concept repeated identically but reports differing definitions', () => {
    const concept = sampleSeed().figures[0]!.concepts[0]!;
    const same = sampleSeed();
    same.figures[1]!.concepts.push({ ...concept });
    expect(validateContent(same)).toEqual([]);

    const different = sampleSeed();
    different.figures[1]!.concepts.push({ ...concept, meaning: 'Başka bir anlam' });
    expect(validateContent(different)).toContain('y: concept "kavram" is defined differently than in x');
  });
});

describe('validateContent: consistency', () => {
  it('reports one place with different names', () => {
    const seed = sampleSeed();
    seed.figures[1]!.journey[1]!.place.historicName = 'Bizans';
    expect(validateContent(seed)).toContain('y: place "istanbul" has a different name than in x');
  });

  it('reports a reign that ends before it starts', () => {
    const seed = sampleSeed();
    seed.figures[1]!.reign = { from: 1530, to: 1500 };
    expect(validateContent(seed)).toContain('y: reign ends before it starts');
  });

  it('reports link markup that does not follow the rules', () => {
    const seed = sampleSeed();
    seed.figures[1]!.actions[0]!.cause = 'Bozuk [[x:abc|bağlantı]] ve [[f:Y|büyük harf]].';
    expect(validateContent(seed)).toContain('y: malformed link markup "[[x:abc|bağlantı]]"');
    expect(validateContent(seed)).toContain('y: malformed link markup "[[f:Y|büyük harf]]"');
  });
});

describe('figure schema: boundaries', () => {
  it('rejects empty place names', () => {
    expect(figureSchema.safeParse(figureSeed('x', { birth: { year: 1500, place: '' } })).success).toBe(false);
  });

  it('rejects a generation date that is not a date', () => {
    const seed = figureSeed('x');
    expect(figureSchema.safeParse({ ...seed, generation: { ...seed.generation, date: 'yesterday' } }).success).toBe(false);
  });

  it('accepts only http and https source addresses', () => {
    const seed = figureSeed('x');
    const withUrl = (url: string) => ({ ...seed, sources: [{ ...seed.sources[0]!, url }, seed.sources[1]!] });
    expect(figureSchema.safeParse(withUrl('javascript:alert(1)')).success).toBe(false);
    expect(figureSchema.safeParse(withUrl('ftp://example.org/x')).success).toBe(false);
    expect(figureSchema.safeParse(withUrl('https://example.org/x')).success).toBe(true);
  });
});

describe('buildDatabase: failures are loud', () => {
  it('fails instead of silently dropping a duplicate row', () => {
    const seed = sampleSeed();
    seed.figures[1]!.actions[1]!.id = 'ilk';
    expect(() => buildDatabase(SQL, seed, BUILT_AT)).toThrow(/UNIQUE constraint failed: action/);
  });

  it('enforces references between tables', () => {
    const seed = sampleSeed();
    seed.figures[0]!.relations.push({ to: 'nobody', type: 'child_of', note: 'n' });
    expect(() => buildDatabase(SQL, seed, BUILT_AT)).toThrow(/FOREIGN KEY constraint failed/);
  });

  it('closes the database when building fails', () => {
    const close = vi.spyOn(SQL.Database.prototype, 'close');
    const seed = sampleSeed();
    seed.figures[1]!.actions[1]!.id = 'ilk';
    expect(() => buildDatabase(SQL, seed, BUILT_AT)).toThrow();
    expect(close).toHaveBeenCalledTimes(1);
  });

  it('still merges one place visited by several figures', () => {
    const db = buildDatabase(SQL, sampleSeed(), BUILT_AT);
    expect(db.exec("SELECT COUNT(*) FROM place WHERE slug = 'istanbul'")[0]!.values[0]![0]).toBe(1);
    db.close();
  });
});

describe('suggested journeys', () => {
  it('only name figures that exist in the content', () => {
    const figuresDir = join(__dirname, '..', '..', 'content', 'figures');
    for (const journey of SUGGESTED_JOURNEYS) {
      expect(existsSync(join(figuresDir, `${journey.from}.json`)), journey.from).toBe(true);
      expect(existsSync(join(figuresDir, `${journey.to}.json`)), journey.to).toBe(true);
    }
  });
});
